import assert from "node:assert/strict";
import { send, evaluate, waitFor, click, fill, shot, errors, close } from "./cdp.mjs";
const origin = process.env.SITELOG_TEST_ORIGIN || "http://localhost:4173";
await send("Page.navigate", { url: origin + "/sitelog/" });
await waitFor("document.querySelector('.current-job')");
await evaluate(`(async()=>{const root=new URL('./',document.querySelector('script[type=module][src]').src).href;const a=await import(root+'mock-auth.mjs');const s=await import(root+'store.mjs');await s.put('contacts',{id:'navigation-client',name:'Harbour Client',active:true,roles:['customer']});const job=await s.get('jobs','harbour');await s.put('jobs',{...job,customerId:'navigation-client'});await a.switchPersona('morgan');})()`);
await send("Page.reload");
await waitFor("document.querySelector('.current-job')");
await click('.sidebar [data-action="office-tab:quotes"]');
await waitFor("document.querySelector('h1').textContent==='Quotes'");
assert.equal(await evaluate("document.querySelectorAll('.sidebar .office-nav-group').length"), 5);
await click('[data-action="new-job"]');
await waitFor("document.querySelector('main .form-page form')");
assert.equal(await evaluate("!!document.querySelector('dialog[open]')"), false);
await fill('#dialog [name="name"]', 'Preserved input');
await evaluate("window.dispatchEvent(new Event('focus'))");
await waitFor("document.querySelector('#dialog [name=name]').value==='Preserved input'");
await click('#dialog [data-action="close"]');
await waitFor("!document.querySelector('.form-page')");
await click('[data-action="nav:today"]');
await waitFor("document.querySelector('.current-job')");
await click('[data-action="time"]');
await waitFor("document.querySelector('#time-form [role=combobox]')");
await evaluate("document.querySelector('#time-form [role=combobox]').focus()");
await fill('#time-form [role=combobox]', '');
assert.ok(await evaluate("document.querySelector('#time-form [role=option] .job-client')?.textContent.length>0"));
await fill('#time-form [role=combobox]', 'Harbour Client');
assert.equal(await evaluate("document.querySelectorAll('#time-form [role=option]').length"), 1);
assert.equal(await evaluate("document.querySelector('#time-form [role=option] .job-client').textContent"), 'Harbour Client');
await fill('#time-form [role=combobox]', 'no such site');
assert.equal(await evaluate("document.querySelectorAll('#time-form [role=option]').length"), 0);
await fill('#time-form [role=combobox]', '');
const expected = await evaluate("document.querySelector('#time-form select[name=jobId] option').value");
await send('Input.dispatchKeyEvent', {type:'keyDown',key:'ArrowDown'});
await send('Input.dispatchKeyEvent', {type:'keyDown',key:'Enter'});
assert.equal(await evaluate("document.querySelector('#time-form select[name=jobId]').value"), expected);
await send('Emulation.setDeviceMetricsOverride', {width:320,height:740,deviceScaleFactor:1,mobile:true});
assert.equal(await evaluate("document.documentElement.scrollWidth <= innerWidth && document.querySelector('.form-page').scrollWidth <= document.querySelector('.form-page').clientWidth"), true);
await shot('/tmp/sitelog-navigation-mobile.png');
await click('#dialog [data-action="close"]');
await waitFor("!document.querySelector('.form-page')");
await click('[data-action="nav:office"]');
await waitFor("document.querySelector('.mobile-office-menu')");
assert.equal(await evaluate("getComputedStyle(document.querySelector('.mobile-office-menu')).display"), 'block');
assert.deepEqual(errors, []);
console.log('PASS: grouped office navigation, page forms, preserved input, searchable job combobox, keyboard selection and mobile layout');
close();
